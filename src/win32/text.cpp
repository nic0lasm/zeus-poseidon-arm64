const uint16_t* high = k1252;
int current = 1252;

// An unassigned byte keeps its value (U+0080 to U+009F).
uint32_t code_point(uint8_t byte) {
    if (byte < 0x80) return byte;
    return high[byte - 0x80] ? high[byte - 0x80] : byte;
}

